import { readFileSync } from "node:fs";

export type ThemeName = "washi" | "sumi";
export type Themed = Record<ThemeName, string>;

export interface Token<V = string> {
  name: string;
  value: V;
  usage?: string;
}

export interface FontFace {
  family: string;
  file: string;
  weight: string;
  style: string;
  unicodeRange?: string;
}

export interface TypeStyle {
  name: string;
  fontSize: string;
  /** Smallest size of a fluid style; with fontSizeFluid, sizes become clamp(min, fluid, fontSize). */
  fontSizeMin?: string;
  fontSizeFluid?: string;
  lineHeight: number;
  fontWeight: number;
  letterSpacing?: string;
  /** Tracking when the style is set vertically (writing-mode: vertical-rl). */
  letterSpacingVertical?: string;
  sample: string;
  usage: string;
}

export interface TypeGroup {
  name: string;
  family: string;
  styles: TypeStyle[];
}

interface TokenGroup<V = string> {
  note?: string;
  tokens: Token<V>[];
}

export interface TokenFile {
  name: string;
  version: number;
  color: { themes: { id: ThemeName; name: string }[]; tokens: Token<Themed>[] };
  type: { fonts: FontFace[]; families: Record<string, string>; groups: TypeGroup[] };
  spacing: TokenGroup;
  radius: TokenGroup;
  stroke: TokenGroup;
  control: TokenGroup;
  layout: TokenGroup;
  shadow: TokenGroup<string | Themed>;
  texture: TokenGroup;
  marker: TokenGroup;
  glyph: TokenGroup;
  motion: TokenGroup;
  underline: TokenGroup;
  zIndex: TokenGroup;
}

export const THEMES: readonly ThemeName[] = ["washi", "sumi"];
export const TOKENS_PATH = "src/tokens/tokens.json";
export const VENDOR_FONTS_PATH = "src/tokens/vendor-fonts.json";

/** Token groups that hold a single value per token (not per theme). */
const SCALAR_GROUPS = [
  "spacing",
  "radius",
  "stroke",
  "control",
  "layout",
  "texture",
  "marker",
  "glyph",
  "motion",
  "underline",
  "zIndex",
] as const;

export function readTokens(path = TOKENS_PATH): TokenFile {
  return JSON.parse(readFileSync(path, "utf8")) as TokenFile;
}

export function readVendorFonts(path = VENDOR_FONTS_PATH): FontFace[] {
  return JSON.parse(readFileSync(path, "utf8")) as FontFace[];
}

/** Families that only ship in the opt-in fonts-jp.css (large unicode-range sliced sets). */
const JP_FAMILIES = new Set(["Zen Old Mincho"]);

/** Font faces split into the default set (fonts.css) and the opt-in Japanese set (fonts-jp.css). */
export function fontSets(tokens: TokenFile): { core: FontFace[]; jp: FontFace[] } {
  const all = [...tokens.type.fonts, ...readVendorFonts()];
  return {
    core: all.filter((font) => !JP_FAMILIES.has(font.family)),
    jp: all.filter((font) => JP_FAMILIES.has(font.family)),
  };
}

function isThemed(value: string | Themed): value is Themed {
  return typeof value !== "string";
}

function declarations(entries: [string, string | number][], indent = "  "): string {
  return entries.map(([name, value]) => `${indent}--${name}: ${String(value)};`).join("\n");
}

/** Custom properties of one theme: colours and themed shadows. */
function themeEntries(tokens: TokenFile, theme: ThemeName): [string, string][] {
  const colors = tokens.color.tokens.map((t): [string, string] => [t.name, t.value[theme]]);
  const shadows = tokens.shadow.tokens
    .filter((t) => isThemed(t.value))
    .map((t): [string, string] => [t.name, (t.value as Themed)[theme]]);
  return [...colors, ...shadows];
}

/** Custom properties shared by both themes: scales, fonts and type styles. */
function scalarEntries(tokens: TokenFile): [string, string | number][] {
  const scales = SCALAR_GROUPS.flatMap((group) =>
    tokens[group].tokens.map((t): [string, string] => [t.name, t.value]),
  );
  const flatShadows = tokens.shadow.tokens
    .filter((t): t is Token => !isThemed(t.value))
    .map((t): [string, string] => [t.name, t.value]);
  const families = Object.entries(tokens.type.families).map(([name, value]): [string, string] => [
    `font-${name}`,
    value,
  ]);
  const type = tokens.type.groups.flatMap((group) =>
    group.styles.flatMap((style): [string, string | number][] => [
      [`text-${style.name}-family`, `var(--font-${group.family})`],
      [
        `text-${style.name}-size`,
        style.fontSizeMin && style.fontSizeFluid
          ? `clamp(${style.fontSizeMin}, ${style.fontSizeFluid}, ${style.fontSize})`
          : style.fontSize,
      ],
      [`text-${style.name}-leading`, style.lineHeight],
      [`text-${style.name}-weight`, style.fontWeight],
      [`text-${style.name}-tracking`, style.letterSpacing ?? "0"],
      ...(style.letterSpacingVertical
        ? [
            [`text-${style.name}-tracking-vertical`, style.letterSpacingVertical] as [
              string,
              string,
            ],
          ]
        : []),
    ]),
  );
  return [...scales, ...flatShadows, ...families, ...type];
}

const GENERATED = "Generated by scripts/build-tokens.ts from src/tokens/tokens.json. Do not edit.";

export function tokensCss(tokens: TokenFile): string {
  const washi = declarations(themeEntries(tokens, "washi"));
  const sumi = declarations(themeEntries(tokens, "sumi"));
  return `/* ${GENERATED} */

:root {
${declarations(scalarEntries(tokens))}
}

/* washi (cream) is the default theme; "auto" starts light and follows the system below. */
:root,
[data-theme="washi"],
[data-theme="auto"],
.ol-auto-theme {
  color-scheme: light;
${washi}
}

[data-theme="sumi"] {
  color-scheme: dark;
${sumi}
}

@media (prefers-color-scheme: dark) {
  [data-theme="auto"],
  .ol-auto-theme {
    color-scheme: dark;
${declarations(themeEntries(tokens, "sumi"), "    ")}
  }
}
`;
}

/**
 * One @font-face per font file. `base` replaces the leading "fonts/" of each file path,
 * so the same list can point at the package's fonts/ from dist/ or from src/styles/.
 */
export function fontsCss(fonts: FontFace[], base: string): string {
  const faces = fonts.map((font) => {
    const lines = [
      `  font-family: "${font.family}";`,
      `  src: url("${font.file.replace(/^fonts\//, base)}") format("woff2");`,
      `  font-weight: ${font.weight};`,
      `  font-style: ${font.style};`,
      "  font-display: swap;",
    ];
    if (font.unicodeRange) lines.push(`  unicode-range: ${font.unicodeRange};`);
    return `@font-face {\n${lines.join("\n")}\n}`;
  });
  return `/* Generated by scripts/build-tokens.ts. Do not edit. */\n\n${faces.join("\n\n")}\n`;
}

export function tokensTs(tokens: TokenFile): string {
  const record = <V>(list: Token<V>[]) =>
    Object.fromEntries(list.map((t) => [t.name, t.value])) as Record<string, V>;

  const data = {
    themes: THEMES,
    color: record(tokens.color.tokens),
    font: tokens.type.families,
    text: Object.fromEntries(
      tokens.type.groups.flatMap((group) =>
        group.styles.map((style) => [
          style.name,
          {
            family: group.family,
            fontSize: style.fontSize,
            ...(style.fontSizeMin && { fontSizeMin: style.fontSizeMin }),
            ...(style.fontSizeFluid && { fontSizeFluid: style.fontSizeFluid }),
            lineHeight: style.lineHeight,
            fontWeight: style.fontWeight,
            letterSpacing: style.letterSpacing ?? "0",
          },
        ]),
      ),
    ),
    space: record(tokens.spacing.tokens),
    radius: record(tokens.radius.tokens),
    stroke: record(tokens.stroke.tokens),
    control: record(tokens.control.tokens),
    layout: record(tokens.layout.tokens),
    shadow: record(tokens.shadow.tokens),
    texture: record(tokens.texture.tokens),
    marker: record(tokens.marker.tokens),
    glyph: record(tokens.glyph.tokens),
    motion: record(tokens.motion.tokens),
    underline: record(tokens.underline.tokens),
    zIndex: record(tokens.zIndex.tokens),
  };

  return `// ${GENERATED}

export const tokens = ${JSON.stringify(data, null, 2)} as const;

export type Tokens = typeof tokens;
export type ThemeName = Tokens["themes"][number];
export type ColorToken = keyof Tokens["color"];
export type FontToken = keyof Tokens["font"];
export type TextStyle = keyof Tokens["text"];
export type SpaceToken = keyof Tokens["space"];
export type RadiusToken = keyof Tokens["radius"];
export type StrokeToken = keyof Tokens["stroke"];
export type ControlToken = keyof Tokens["control"];
export type LayoutToken = keyof Tokens["layout"];
export type ShadowToken = keyof Tokens["shadow"];
export type ZIndexToken = keyof Tokens["zIndex"];
`;
}
