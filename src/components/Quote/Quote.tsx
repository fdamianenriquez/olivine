import {
  Children,
  type ComponentPropsWithoutRef,
  forwardRef,
  Fragment,
  type HTMLAttributes,
  isValidElement,
  type ReactNode,
  type Ref,
  useEffect,
} from "react";

import { cx } from "../../utils/cx";
import { devWarn } from "../../utils/dev";

export type QuoteVariant = "block" | "pull";
export type QuoteSize = "m" | "l";

export interface QuoteProps extends Omit<HTMLAttributes<HTMLElement>, "lang"> {
  /**
   * The quoted text. A string becomes one `<p>`; pass several `<p>` elements for a
   * multi-paragraph quote (the marks open on the first and close on the last).
   */
  children?: ReactNode;
  /**
   * `block` is a quote inside running content (body text, a hairline edge); `pull` is a display
   * statement in Big Shoulders for testimonials, bands and slides.
   * @default "block"
   */
  variant?: QuoteVariant;
  /**
   * `pull` only: `m` uses the `h1` style (44px), `l` uses `display-m` (40 to 64px). Ignored, with a
   * development warning, on `block`.
   * @default "m"
   */
  size?: QuoteSize;
  /** Who said it: a name or a role. Plain text; wrap a foreign name in `<span lang>`. */
  author?: ReactNode;
  /** Role, place or date, in the secondary ink. */
  detail?: ReactNode;
  /** The title of the work the quote comes from, rendered in `<cite>`. Never a person's name. */
  source?: ReactNode;
  /** Replaces `author`, `detail` and `source` with your own caption content. */
  attribution?: ReactNode;
  /** An `Avatar` shown before the attribution. It is hidden from assistive technology. */
  avatar?: ReactNode;
  /** URL of the source, set as the `cite` attribute of the `<blockquote>`. Metadata only. */
  cite?: string;
  /** Language of the quoted text, set on the `<blockquote>`. It also selects the quotation marks. */
  lang?: string;
  /**
   * Shows the quotation marks, drawn by CSS (not read, not copied).
   * @default true on `pull`, false on `block`
   */
  marks?: boolean;
  /** `paper` fill, hairline border and padding, for a photo or a busy ground. */
  framed?: boolean;
  /** The quote repeats text already on the page: hides it from assistive technology. */
  repeated?: boolean;
}

const has = (node: ReactNode): boolean => node != null && node !== false && node !== "";

const INTERACTIVE = new Set(["a", "button", "input", "select", "textarea"]);

/** True when a React element tree holds a link or form control (custom components are not inspected). */
function containsInteractive(node: ReactNode): boolean {
  return Children.toArray(node).some(
    (child) =>
      isValidElement<{ href?: string; children?: ReactNode }>(child) &&
      ((typeof child.type === "string" && INTERACTIVE.has(child.type)) ||
        child.props.href !== undefined ||
        containsInteractive(child.props.children)),
  );
}

/** Joins the present caption parts with a real space, so they are spoken as separate words. */
function joinParts(parts: (ReactNode | false)[]): ReactNode {
  return parts
    .filter((part): part is ReactNode => part !== false)
    .map((part, i) => (
      <Fragment key={i}>
        {i > 0 && <span className="ol-quote__space"> </span>}
        {part}
      </Fragment>
    ));
}

/**
 * Words from another voice, with their attribution.
 *
 * Without attribution it renders a bare `<blockquote>`; with `author`, `detail`, `source` or
 * `attribution` it renders a `<figure>` holding the `<blockquote>` and a `<figcaption>`, so the
 * attribution is never inside the quoted text. `lang` and `cite` go on the `<blockquote>`;
 * `className`, `ref` and the other native attributes go on the root. Quotation marks, the dash
 * and the dots are generated by CSS. Quote is static: no states, no motion, no tab stop.
 */
export const Quote = forwardRef<HTMLElement, QuoteProps>(function Quote(
  {
    children,
    variant = "block",
    size,
    author,
    detail,
    source,
    attribution,
    avatar,
    cite,
    lang,
    marks,
    framed = false,
    repeated = false,
    className,
    ...rest
  },
  ref,
) {
  const hasAttribution = has(attribution);
  const hasWho = hasAttribution || has(author) || has(detail) || has(source);
  const hasAvatar = has(avatar);
  const isPull = variant === "pull";
  const showMarks = marks ?? isPull;
  const sizeWarning = size !== undefined && !isPull;
  const interactiveInRepeated =
    repeated &&
    [children, author, detail, source, attribution, avatar].some((part) =>
      containsInteractive(part),
    );
  const orphanAvatar = hasAvatar && !has(author) && !hasAttribution;

  useEffect(() => {
    if (sizeWarning) devWarn("Quote", '`size` only applies to variant="pull"; it is ignored.');
  }, [sizeWarning]);
  useEffect(() => {
    if (interactiveInRepeated) {
      devWarn("Quote", "A `repeated` quote is hidden, but a link or control inside it is not.");
    }
  }, [interactiveInRepeated]);
  useEffect(() => {
    if (orphanAvatar)
      devWarn("Quote", "`avatar` is hidden from assistive technology; add `author`.");
  }, [orphanAvatar]);

  const rootClass = cx(
    "ol-quote",
    `ol-quote--${variant}`,
    isPull && size === "l" && "ol-quote--size-l",
    showMarks && "ol-quote--marks",
    framed && "ol-quote--framed",
    className,
  );
  const body =
    typeof children === "string" || typeof children === "number" ? <p>{children}</p> : children;

  if (!hasWho && !hasAvatar) {
    return (
      <blockquote
        {...rest}
        ref={ref as Ref<HTMLQuoteElement>}
        className={cx(rootClass, "ol-quote__body")}
        cite={cite}
        lang={lang}
        aria-hidden={repeated ? true : rest["aria-hidden"]}
      >
        {body}
      </blockquote>
    );
  }

  return (
    <figure
      {...rest}
      ref={ref}
      className={rootClass}
      aria-hidden={repeated ? true : rest["aria-hidden"]}
    >
      <blockquote className="ol-quote__body" cite={cite} lang={lang}>
        {body}
      </blockquote>
      <figcaption className="ol-quote__caption">
        {hasAvatar && (
          <span className="ol-quote__avatar" aria-hidden="true">
            {avatar}
          </span>
        )}
        <span className="ol-quote__who">
          {hasAttribution
            ? attribution
            : joinParts([
                has(author) && <span className="ol-quote__author">{author}</span>,
                has(detail) && <span className="ol-quote__detail">{detail}</span>,
                has(source) && <cite className="ol-quote__source">{source}</cite>,
              ])}
        </span>
      </figcaption>
    </figure>
  );
});

export type InlineQuoteProps = ComponentPropsWithoutRef<"q">;

/**
 * A short quotation inside a sentence, in `<q>`. It adds no box or colour: the browser draws the
 * marks for the language and the nesting depth. `lang` is the language of the quoted words and
 * `cite` the URL of the source (metadata only).
 */
export const InlineQuote = forwardRef<HTMLQuoteElement, InlineQuoteProps>(function InlineQuote(
  { className, ...rest },
  ref,
) {
  return <q ref={ref} className={cx("ol-quote-inline", className)} {...rest} />;
});
